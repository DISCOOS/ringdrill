#!/usr/bin/env node
// Records what the MCP compiler bundle was built from, so staleness is a fact
// rather than a guess.
//
//   node tools/mcp-bundle-stamp.mjs write <bundle.js.deps>   (from `make mcp-bundle`)
//   node tools/mcp-bundle-stamp.mjs check                    (what the test does)
//
// The bundle is committed because a Netlify build has no Dart SDK (ADR-0060), which
// means nothing rebuilds it automatically and a stale one serves *old compiler
// behaviour* from /mcp with no other symptom. So something has to notice. The first
// attempt compared the bundle's mtime against the newest .dart file under a
// hand-listed set of roots, and it was wrong twice over:
//
//   - It watched the wrong files. `lib/l10n/` was one of the roots, but the
//     Flutter-generated app_localizations*.dart in there is not in the bundle's
//     dependency graph at all — the bundle reaches the *headless* subset
//     (headless_labels.dart, headless_labels.g.dart) and nothing else from l10n.
//     A file the bundle cannot depend on was failing the check.
//   - It compared mtimes. `flutter gen-l10n` rewrites app_localizations*.dart
//     unconditionally with byte-identical content, so `make i18n`, `make build` and
//     `make labels` each moved that mtime forward and turned the suite red with
//     nothing stale. `git checkout`, `git stash` and branch switches do the same.
//     It fired three times in one session; two were false, and a guard that cries
//     wolf is one people learn to run past.
//
// The dependency list comes from dart2js itself — the `.deps` file it writes beside
// the bundle — so the closure cannot drift from what was actually compiled, and a
// new file entering the graph is covered the moment it exists rather than when
// somebody remembers to add a root here.
//
// Only in-repo sources are hashed. The other ~530 entries are the pub cache and the
// Dart SDK, whose absolute paths are specific to one machine; `pubspec.lock` pins
// those, so hashing it covers a dependency bump portably.
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative, sep } from 'node:path';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');

/// Committed beside the bundle, and regenerated with it.
export const STAMP_PATH = join(
    repoRoot,
    'netlify',
    'functions',
    'lib',
    'mcp-compiler-bundle.sources.json',
);

/// Hashed alongside the sources so a dependency bump counts as a change, since the
/// pub-cache paths in `.deps` are not portable enough to hash directly.
const LOCKFILE = 'pubspec.lock';

async function sha256(path) {
    return createHash('sha256')
        .update(await readFile(join(repoRoot, path)))
        .digest('hex');
}

/// The in-repo `.dart` files dart2js actually compiled, repo-relative and sorted.
///
/// `.dart_tool/package_config.json` is in the list and deliberately dropped: it is
/// generated by `pub get`, is not committed, and says nothing `pubspec.lock` does
/// not say more stably.
function sourcesFromDeps(deps) {
    const prefix = `file://${repoRoot}${sep}`;
    return deps
        .split('\n')
        .filter((line) => line.startsWith(prefix))
        .map((line) => relative(repoRoot, fileURLToPath(line.trim())))
        .filter((path) => path.endsWith('.dart'))
        .filter((path) => !path.startsWith(`.dart_tool${sep}`))
        .sort();
}

/// Writes the stamp from a dart2js `.deps` file.
export async function write(depsPath) {
    const paths = sourcesFromDeps(await readFile(depsPath, 'utf8'));
    if (paths.length === 0) {
        throw new Error(
            `${depsPath} listed no in-repo Dart sources — the bundle cannot have ` +
                'been built from this checkout',
        );
    }

    const files = {};
    for (const path of [...paths, LOCKFILE]) {
        files[path] = await sha256(path);
    }

    const stamp = {
        '//': [
            'Generated by `make mcp-bundle` from the dart2js .deps file. Do not',
            'edit. Records what netlify/functions/lib/mcp-compiler-bundle.js was',
            'compiled from, so netlify/tests/mcp-compiler-parity.test.mjs can tell',
            'a stale bundle from a rebuilt one by content rather than by mtime.',
        ].join(' '),
        files,
    };
    await writeFile(STAMP_PATH, `${JSON.stringify(stamp, null, 2)}\n`, 'utf8');
    return paths.length;
}

/// Sources whose content no longer matches the stamp.
///
/// A file *added* to the closure since the last build is caught transitively rather
/// than directly: something already in the graph had to import it, and that import
/// changed that file's hash. A file removed from the graph still lingers in the
/// stamp until the next build, which is harmless — it is still a source, and if it
/// changes, rebuilding is the right answer anyway.
export async function check() {
    let stamp;
    try {
        stamp = JSON.parse(await readFile(STAMP_PATH, 'utf8'));
    } catch (error) {
        if (error.code !== 'ENOENT') throw error;
        return {
            missingStamp: true,
            changed: [],
        };
    }

    const changed = [];
    for (const [path, expected] of Object.entries(stamp.files ?? {})) {
        let actual;
        try {
            actual = await sha256(path);
        } catch (error) {
            if (error.code !== 'ENOENT') throw error;
            changed.push(`${path} (deleted)`);
            continue;
        }
        if (actual !== expected) changed.push(path);
    }
    return { missingStamp: false, changed };
}

// CLI entry. Kept below the exports so the test can import without running it.
if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const [command, argument] = process.argv.slice(2);
    if (command === 'write') {
        if (!argument) {
            console.error('usage: mcp-bundle-stamp.mjs write <bundle.js.deps>');
            process.exit(2);
        }
        const count = await write(argument);
        console.log(
            `  stamped ${count} source files -> ` +
                `${relative(repoRoot, STAMP_PATH)}`,
        );
    } else if (command === 'check') {
        const { missingStamp, changed } = await check();
        if (missingStamp) {
            console.error(
                `${relative(repoRoot, STAMP_PATH)} is missing — run ` +
                    '`make mcp-bundle`',
            );
            process.exit(1);
        }
        if (changed.length) {
            console.error(
                `the bundle is stale; these have changed since it was built:\n  ` +
                    `${changed.join('\n  ')}\nRun \`make mcp-bundle\`.`,
            );
            process.exit(1);
        }
        console.log('the bundle is current');
    } else {
        console.error('usage: mcp-bundle-stamp.mjs write <deps> | check');
        process.exit(2);
    }
}
